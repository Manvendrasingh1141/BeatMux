export const timeToPixels = (time, pixelsPerSecond) => {
  return time * pixelsPerSecond;
};

export const pixelsToTime = (pixels, pixelsPerSecond) => {
  return pixels / pixelsPerSecond;
};

export const durationToPixels = (duration, pixelsPerSecond) => {
  return duration * pixelsPerSecond;
};

export const pixelsToDuration = (pixels, pixelsPerSecond) => {
  return pixels / pixelsPerSecond;
};
